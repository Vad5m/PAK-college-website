import os
from flask import Flask, session
from flask_minify import Minify

from config import (SECRET_KEY, UPLOAD_FOLDER, WP_UPLOAD_FOLDER,
                    EDITOR_UPLOAD_FOLDER, EDITOR_DOCS_FOLDER, HOST, PORT, DEBUG)
from db import get_db, init_db, init_stats_db, create_default_admin
from utils import get_media_url
from routes import bp, start_history_collector


def create_app():
    app = Flask(__name__)
    app.secret_key = SECRET_KEY
    Minify(app=app, html=True, js=True, cssless=True)

    app.config["UPLOAD_FOLDER"] = UPLOAD_FOLDER
    app.config["EDITOR_UPLOAD_FOLDER"] = EDITOR_UPLOAD_FOLDER
    app.config["EDITOR_DOCS_FOLDER"] = EDITOR_DOCS_FOLDER
    app.config["MAX_CONTENT_LENGTH"] = 100 * 1024 * 1024

    for d in (UPLOAD_FOLDER, WP_UPLOAD_FOLDER, EDITOR_UPLOAD_FOLDER, EDITOR_DOCS_FOLDER):
        os.makedirs(d, exist_ok=True)

    init_stats_db()
    init_db()
    create_default_admin()
    start_history_collector()

    app.register_blueprint(bp)

    @app.context_processor
    def inject_admin():
        if "admin_id" in session:
            conn = get_db()
            admin = conn.execute(
                "SELECT level FROM admins WHERE id = ?", (session["admin_id"],)
            ).fetchone()
            conn.close()
            if admin:
                return {"is_admin": True, "user_level": admin["level"],
                        "username": session.get("username", "")}
        return {"is_admin": False, "user_level": 0, "username": ""}

    @app.template_filter("media_url")
    def media_url_filter(media_path):
        if not media_path:
            return ""
        if ";" in media_path:
            return ";".join(get_media_url(p) for p in media_path.split(";") if p)
        return get_media_url(media_path)

    return app


app = create_app()

